def update_task_status(task_id: str, status: str, details: Optional[str] = None) -> Dict[str, Any]:
    """
    Update the status of a task in the plan.
    
    Args:
        task_id: The ID of the task to update
        status: New status ("pending", "in_progress", "completed", "blocked")
        details: Optional details about the update
        
    Returns:
        Updated task information
    """
    return {
        "task_id": task_id,
        "status": status,
        "details": details
    }


